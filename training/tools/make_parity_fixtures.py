"""Writes app/integration_test/parity_fixtures.dart: test photos plus the
probabilities Python gets for them, so the on-device test can check the
phone (Dart preprocessing + tflite_flutter + decision rule) gives the same
answer as the evaluated pipeline.

    python -m tools.make_parity_fixtures --config sandbox/public/work/config.yaml [--per-class 2]

Python side mirrors the app exactly: EXIF rotation, centre square crop,
area-average resize to the model size, RGB 0-255, the app's model.tflite,
then src.decision.decide.
"""

from __future__ import annotations

import argparse
import base64
import io
import json

import numpy as np
import pandas as pd
import tensorflow as tf
from PIL import Image

from src.config import TRAINING_DIR, Config
from src.decision import decide
from src.quality import load_rgb

APP = TRAINING_DIR.parent / "app"
PNG_SIDE = 384  # lossless fixtures are stored at this size to keep the file small


def app_input(path_or_image, size: int) -> np.ndarray:
    im = path_or_image if isinstance(path_or_image, Image.Image) else load_rgb(path_or_image)
    s = min(im.size)
    left, top = (im.width - s) // 2, (im.height - s) // 2
    im = im.crop((left, top, left + s, top + s)).resize((size, size), Image.BOX)
    return np.asarray(im, dtype=np.float32)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True)
    ap.add_argument("--per-class", type=int, default=2)
    a = ap.parse_args()
    cfg = Config(a.config)

    meta = json.loads((APP / "assets/model/model_meta.json").read_text())
    interp = tf.lite.Interpreter(model_path=str(APP / "assets/model/model.tflite"))
    interp.allocate_tensors()
    inp, out = interp.get_input_details()[0], interp.get_output_details()[0]

    test = pd.read_csv(cfg.path_of("splits_dir") / "test.csv")
    picked = test.groupby("class_id", group_keys=False).apply(
        lambda g: g.sample(min(a.per_class, len(g)), random_state=0))

    def predict(image_or_path):
        interp.set_tensor(inp["index"], app_input(image_or_path, meta["input_size"])[None])
        interp.invoke()
        return interp.get_tensor(out["index"])[0].astype(float)

    entries = []
    for n, row in enumerate(picked.itertuples()):
        src = cfg.path_of("raw_dir") / row.file
        # Every photo as its original JPEG (real camera path: different JPEG
        # decoders on each side). Every other photo also as a lossless PNG
        # (identical pixels on both sides: checks resize + TFLite + rule exactly).
        variants = [("jpg", src.read_bytes(), src)]
        if n % 2 == 0:
            im = load_rgb(src)
            im = im.resize((PNG_SIDE, round(im.height * PNG_SIDE / im.width)), Image.BOX)
            buf = io.BytesIO()
            im.save(buf, format="PNG")
            variants.append(("png", buf.getvalue(), Image.open(io.BytesIO(buf.getvalue())).convert("RGB")))
        for fmt, data, source in variants:
            probs = predict(source)
            d = decide(probs, cfg.labels, meta["t_conf"], meta["t_spoil"])
            entries.append({
                "id": row.image_id, "true": row.class_id, "format": fmt, "data": base64.b64encode(data).decode(),
                "probs": [round(p, 6) for p in probs], "category": d.category, "reason": d.reason,
            })

    lines = [
        "// GENERATED by training/tools/make_parity_fixtures.py. Do not edit.",
        f"// model: {meta['model_version']}",
        "",
        "const parityModelVersion = '" + meta["model_version"] + "';",
        "",
        "const parityFixtures = <Map<String, Object>>[",
    ]
    for e in entries:
        lines += [
            "  {",
            f"    'id': '{e['id']}',",
            f"    'format': '{e['format']}',",
            f"    'true': '{e['true']}',",
            f"    'category': '{e['category']}',",
            f"    'reason': '{e['reason']}',",
            f"    'probs': <double>{json.dumps(e['probs'])},",
            f"    'data': '{e['data']}',",
            "  },",
        ]
    lines.append("];")
    dst = APP / "integration_test" / "parity_fixtures.dart"
    dst.parent.mkdir(exist_ok=True)
    dst.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(entries)} fixtures -> {dst} ({dst.stat().st_size / 1e6:.1f} MB)")
    print(pd.DataFrame(entries)[["id", "format", "true", "category", "reason"]].to_string(index=False))


if __name__ == "__main__":
    main()
